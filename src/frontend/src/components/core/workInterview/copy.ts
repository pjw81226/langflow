export function processExample(task: string): string {
  if (/노하우|기준|순서|점검/.test(task))
    return "예: 먼저 보는 항목과 다음에 확인하는 항목을 적어주세요. 어떤 경우에 다르게 처리하는지도 좋아요.";
  if (/메일|메신저/.test(task))
    return "예: 메일에서 날짜와 요청 사항을 찾고, 변경된 내용은 따로 표시해요. 빠진 내용은 담당자에게 물어봐요.";
  if (/보고|정리|모아/.test(task))
    return "예: 필요한 숫자를 모으고 이전 결과와 비교한 뒤, 달라진 이유를 한 줄로 정리해요.";
  if (/비교|달라/.test(task))
    return "예: 같은 항목끼리 맞춰 보고, 새로 생기거나 바뀐 내용만 따로 적어요.";
  return "예: 필요한 항목을 찾고, 확인할 부분을 따로 표시한 뒤 결과를 정리해요.";
}

